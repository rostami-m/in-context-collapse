#!/usr/bin/env python3
"""Export standard/remap region curves from retained aggregate means only.

The sources do not retain per-query or per-seed records for this sweep. Existing
CI fields are deliberately unused: this exporter neither reconstructs uncertainty
nor infers parsing rates. --check verifies deterministic output without writing.
"""
from __future__ import annotations

import argparse
from decimal import Decimal, ROUND_HALF_UP
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
KS = (0, 1, 2, 4, 8, 16)
SOURCES = (("circuit_shapes.json", "shapes4", "Shapes"),
           ("circuit_cifar.json", "cifar4", "CIFAR-4"))
REGIONS = (("baseline", "Baseline"), ("connector:both", "Connector"),
           ("early:both", "Early"), ("mid:both", "Middle"),
           ("late:both", "Late"), ("all:both", "Capped all"))
MODEL = "Qwen/Qwen2-VL-2B-Instruct"


def number(value, *, leading_zero=True):
    if isinstance(value, bool) or not isinstance(value, (int, Decimal)):
        raise ValueError("accuracy must be a JSON number")
    value = Decimal(value)
    if not value.is_finite() or not 0 <= value <= 1:
        raise ValueError("accuracy must be finite and within [0, 1]")
    text = str(value.quantize(Decimal("0.001"), rounding=ROUND_HALF_UP))
    return text if leading_zero else text.removeprefix("0")


def source_rows(payload, task, label):
    if payload.get("model") != MODEL or payload.get("task") != task or payload.get("arm") != "remove":
        raise ValueError("unexpected region-sweep model, task, or arm")
    if payload.get("ks") != list(KS):
        raise ValueError("region-sweep K grid must be 0/1/2/4/8/16")
    expected = {str(k) for k in KS}
    rows = []
    for key, region in REGIONS:
        for condition in ("standard", "remap"):
            curve = payload.get(key, {}).get(condition)
            if not isinstance(curve, dict) or set(curve) != expected:
                raise ValueError(f"missing or unexpected curve cells: {task}/{key}/{condition}")
        cells = [number(payload[key]["standard"][str(k)], leading_zero=False) + "/" +
                 number(payload[key]["remap"][str(k)], leading_zero=False) for k in KS]
        rows.append(" & ".join((label, region, *cells)) + r" \\")
    return rows


def build_fragments(source_dir):
    header = ["% Generated by scripts/export_region_aggregate_tables.py; do not edit.",
              "% Retained aggregate means only; no reconstructed CIs or parsing rates.",
              "% Region rows use the combined-component arms; component-only arms are separate."]
    blocks, payloads = [], []
    for name, task, label in SOURCES:
        content = (source_dir / name).read_bytes()
        header.append(f"% Source: data/figdata/{name}; SHA256: {hashlib.sha256(content).hexdigest()}")
        payload = json.loads(content, parse_float=Decimal)
        blocks.append(source_rows(payload, task, label))
        payloads.append(payload)
    lines = header + ["% Each numerical cell is standard/remap, rounded to three decimals; leading zeros omitted.",
                      "% Columns: task & region & K0 & K1 & K2 & K4 & K8 & K16."]
    for index, rows in enumerate(blocks):
        if index:
            lines.append(r"\midrule")
        lines.extend(rows)
    compact = header + ["% All accuracy means rounded to three decimals; K=16 only.",
                        "% Columns: region & Shapes standard & Shapes remap & CIFAR standard & CIFAR remap."]
    for key, region in REGIONS:
        cells = [number(payload[key][condition]["16"]) for payload in payloads
                 for condition in ("standard", "remap")]
        compact.append(" & ".join((region, *cells)) + r" \\")
    return {"region_standard_remap.tex": "\n".join(lines) + "\n",
            "region_standard_remap_k16.tex": "\n".join(compact) + "\n"}


def build_fragment(source_dir):
    return build_fragments(source_dir)["region_standard_remap.tex"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=ROOT / "data/figdata")
    parser.add_argument("--out-dir", type=Path, default=ROOT / "paper/revision_results")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatches = []
    for name, content in build_fragments(args.source_dir).items():
        path = args.out_dir / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                mismatches.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if mismatches:
        parser.exit(1, "Generated region rows differ: " + ", ".join(mismatches) + "\n")
    print(f"{'Checked' if args.check else 'Wrote'} 2 aggregate fragments (144 means plus 24 K16 entries)")


if __name__ == "__main__":
    main()
